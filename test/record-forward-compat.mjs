/**
 * Record what the PRE-EXTENSION codec does with post-extension codes.
 *
 * The current-state segment was appended positionally so that a reader which
 * knows nothing about it still resolves the build. That claim is only worth
 * something if it is measured against the reader that actually shipped, so
 * this drives the published build (the one installed in the portfolio's
 * node_modules) and writes down what it produced.
 *
 * Run this ONCE, against a build that predates the extension. Re-running it
 * against a codec that understands the new segment records the wrong thing:
 * the point of the file is what an OLD reader does, and once every reader
 * understands the segment there is nothing left to record.
 *
 *   node test/record-forward-compat.mjs <path-to-old-dist/index.js>
 */

import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fixture = JSON.parse(
  await import("node:fs").then((fs) =>
    fs.readFileSync(resolve(here, "fixtures/build-codes.json"), "utf8"),
  ),
);

const oldDist =
  process.argv[2] ??
  resolve(here, "../../v02/v02-portfolio/node_modules/@v02/metalstorm-core/dist/index.js");

if (!existsSync(oldDist)) {
  console.error(
    `No pre-extension build at ${oldDist}.\n` +
      `Pass the path to an old dist/index.js as an argument.`,
  );
  process.exit(1);
}

const core = await import(pathToFileURL(oldDist).href);
const codec = core.createBuildCodec(fixture.dataset);

const base = "f-5-tiger.20.F8tttt_E8tttt_A8tttt_PC8tttt_IM8tttt";
const cur = "F8_E6_A4_PC2_IM0";

const cases = [
  ["no current segment, unchanged", base],
  ["empty flag slot then current", `${base}..${cur}`],
  ["o flag then current", `${base}.o.${cur}`],
  ["current carrying an aircraft level", `${base}..12_${cur}`],
  ["current with an unknown marker", `${base}..F8_E6_A4_PC-_IM0`],
  ["current on both of two builds", `${base}..${cur}*su-27-flanker.20.F8bbbb..F8_E5`],
  ["current on the second build only", `${base}*su-27-flanker.20.F8bbbb..F8_E5`],
  ["current on a build with no picks", `f-5-tiger.1...F0_E0_A0_PC0_IM0`],
  ["current on a build with no picks and the flag", `f-5-tiger.1..o.F0_E0`],
  ["empty current segment", `${base}..`],
  ["current segment that is only an aircraft level", `${base}..12`],
  ["five builds each with current", [0, 1, 2, 3, 4]
    .map((i) => `${fixture.dataset.aircraft[i].slug}.20..F8_E6`)
    .join("*")],
];

const recorded = cases.map(([name, raw]) => {
  const decoded = codec.read(raw);
  return { name, raw, decoded, reencoded: codec.write(decoded) };
});

const out = {
  "//": [
    "RECORDED FROM THE PRE-EXTENSION CODEC.",
    "",
    "Each entry is what the published build did when handed a code carrying a",
    "current-state segment it had never heard of. This is the evidence that",
    "appending the segment positionally does not break readers that predate",
    "it, taken from the reader that actually shipped rather than argued for.",
    "",
    "NOTE WHAT reencoded SHOWS. An old reader drops the segment on write. A",
    "link generated by the overlay, opened on an old site and edited there,",
    "silently loses its player state. That is why the site parser has to ship",
    "before the overlay emits any new codes.",
    "",
    "DO NOT RE-RECORD THIS AGAINST A CODEC THAT UNDERSTANDS THE SEGMENT.",
    "",
    "It would record a new reader agreeing with itself, which proves nothing.",
    "Once every reader understands the segment this file is history, not a",
    "test subject, and it should be left exactly as it is.",
  ],
  recorded_from: "@v02/metalstorm-core@0.1.0, commit 27edd71",
  cases: recorded,
};

const path = resolve(here, "fixtures/forward-compat.json");
writeFileSync(path, `${JSON.stringify(out, null, 2)}\n`, "utf8");
console.log(`wrote ${path}\n  ${recorded.length} cases recorded from ${oldDist}`);
